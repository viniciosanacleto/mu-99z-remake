package legacy

import (
	"fmt"
	"reflect"
	"strings"

	"github.com/viniciosanacleto/mu-remake/apps/server/internal/config/mutext"
	"github.com/viniciosanacleto/mu-remake/apps/server/internal/config/tomlconf"
)

// Row fills the exported fields of *out with the tokens of l, in field
// order: an int field takes one number ("*" is -1, mutext.Line.Int), a
// string field one token (converted to UTF-8), an array of N elements N
// tokens, and a slice the remaining tokens. Fields tagged `legacy:"-"` are
// skipped and a string field named Comment (or tagged `legacy:"comment"`)
// takes the text after "//" (the Comment column of the originals). Missing tokens are an error;
// extra tokens are an error unless loose is set.
func Row(l mutext.Line, out any, loose bool) error {
	v := reflect.ValueOf(out).Elem()
	next := 0
	if err := fill(l, v, &next); err != nil {
		return err
	}
	if !loose && next < len(l.Tokens) {
		return fmt.Errorf("line %d: %d columns, want %d", l.No, len(l.Tokens), next)
	}
	return nil
}

func fill(l mutext.Line, v reflect.Value, next *int) error {
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() || f.Tag.Get("legacy") == "-" {
			continue
		}
		fv := v.Field(i)
		if f.Tag.Get("legacy") == "comment" || f.Name == "Comment" && fv.Kind() == reflect.String {
			fv.SetString(tomlconf.UTF8(l.Comment))
			continue
		}
		switch fv.Kind() {
		case reflect.Slice:
			for *next < len(l.Tokens) {
				e := reflect.New(fv.Type().Elem()).Elem()
				if err := scalar(l, e, next); err != nil {
					return err
				}
				fv.Set(reflect.Append(fv, e))
			}
		case reflect.Array:
			for j := 0; j < fv.Len(); j++ {
				if err := scalar(l, fv.Index(j), next); err != nil {
					return err
				}
			}
		case reflect.Struct:
			if err := fill(l, fv, next); err != nil {
				return err
			}
		default:
			if err := scalar(l, fv, next); err != nil {
				return err
			}
		}
	}
	return nil
}

func scalar(l mutext.Line, v reflect.Value, next *int) error {
	i := *next
	*next++
	switch v.Kind() {
	case reflect.String:
		s, err := l.String(i)
		if err != nil {
			return err
		}
		v.SetString(tomlconf.UTF8(s))
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		n, err := l.Int(i)
		if err != nil {
			return err
		}
		v.SetInt(int64(n))
	case reflect.Struct:
		*next--
		return fill(l, v, next)
	default:
		return fmt.Errorf("legacy: unsupported field kind %s", v.Kind())
	}
	return nil
}

// Table decodes the rows of a plain table (every line up to "end").
func Table[T any](lines []mutext.Line, loose bool) ([]T, error) {
	return Rows[T](mutext.Table(lines), loose)
}

// Rows decodes every line.
func Rows[T any](lines []mutext.Line, loose bool) ([]T, error) {
	out := make([]T, 0, len(lines))
	for _, l := range lines {
		var r T
		if err := Row(l, &r, loose); err != nil {
			return nil, err
		}
		out = append(out, r)
	}
	return out, nil
}

// File tokenizes a file of the original Data/ format.
func File(path string) ([]mutext.Line, error) {
	return mutext.LoadFile(path)
}

// FirstTokens returns the first token of every table row (single-column
// lists such as BlackList.txt).
func FirstTokens(lines []mutext.Line) []string {
	var out []string
	for _, l := range mutext.Table(lines) {
		out = append(out, tomlconf.UTF8(l.Tokens[0]))
	}
	return out
}

// header is the comment written at the top of every generated file.
func header(sources ...string) string {
	return "# Generated by cmd/configconv from the original MuServer files:\n#   " +
		strings.Join(sources, "\n#   ") + "\n# Edit freely: the server reads this file, not the originals.\n"
}
